def is_complete():
    """检查题库是否已录满（每层 12 题）——界面据此判断能不能开考"""
    return all(len(level["questions"]) == 12 for level in VST_LEVELS)


def total_questions():
    """当前已录入的总题数"""
    return sum(len(level["questions"]) for level in VST_LEVELS)


def estimate_vst(total_correct):
    """VST 标准计分：答对总数 × 100 = 估算词汇量"""
    return total_correct * SCORE_PER_ITEM


